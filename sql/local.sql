
CREATE DATABASE IF NOT EXISTS validagt_pro
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

USE validagt_pro;

CREATE TABLE IF NOT EXISTS personas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    edad INT NOT NULL,
    telefono VARCHAR(8) NOT NULL,
    dpi VARCHAR(13) NOT NULL,
    correo VARCHAR(150) NOT NULL,
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_dpi UNIQUE (dpi),
    CONSTRAINT uq_correo UNIQUE (correo),
    CONSTRAINT chk_edad CHECK (edad BETWEEN 1 AND 120)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS intentos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    resultado ENUM('APROBADO', 'RECHAZADO') NOT NULL,
    motivo ENUM('NINGUNO', 'FORMATO', 'DUPLICADO') NOT NULL,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
